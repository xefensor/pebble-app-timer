#!/usr/bin/env python3
"""Generate bounded native locale resources from the app-owned UTF-8 catalogue."""
from pathlib import Path
import argparse,json
ROOT=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
data=json.loads((ROOT/'src/common/translations.json').read_text());keys=data['native'];languages=data['languages'];words=data['words']
resource=bytearray();ranges=[];maximum=1
for lang in languages:
    row=b''.join(data.get('nativeWords',{}).get(lang,{}).get(key,words[lang][key]).encode('utf-8')+b'\0' for key in keys) if lang!='en' else b''
    ranges.append((len(resource),len(row)));resource.extend(row);maximum=max(maximum,len(row))
assert maximum<=4096,'Native locale exceeds the bounded buffer'
header=['// Generated by scripts/generate-localization.py.','#pragma once',f'#define APP_TEXT_COUNT {len(keys)}',f'#define APP_TEXT_BYTES {maximum}',
 'static const char *const app_languages[]={'+','.join(json.dumps(lang) for lang in languages)+'};',
 'static const char *const app_english[]={'+','.join(json.dumps(key) for key in keys)+'};',
 'static const char *const app_fallback[]={'+','.join(json.dumps(data.get('nativeWords',{}).get('en',{}).get(key,words['en'][key])) for key in keys)+'};',
 'static const uint32_t app_text_ranges[][2]={'+','.join('{%d,%d}'%pair for pair in ranges)+'};','']
outputs={ROOT/'resources/localization.bin':bytes(resource),ROOT/'src/c/generated_localization.h':'\n'.join(header).encode()}
for path,content in outputs.items():
    if args.check:
        if not path.exists() or path.read_bytes()!=content:raise SystemExit(str(path)+' is stale; run python3 scripts/generate-localization.py')
    else:path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(content)
print('Native locale resource: '+str(len(resource))+' bytes; selected-language buffer '+str(maximum)+' bytes')
